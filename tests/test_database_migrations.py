@pytest.mark.parametrize('failure', [RuntimeError, KeyboardInterrupt])
def test_exception_rolls_back_schema_payload_changes_and_version(legacy, monkeypatch, failure):
    repo, path, _ = legacy
    before = snapshot(path)
    def interrupted(connection):
        connection.execute('CREATE TABLE unfinished (id TEXT)')
        connection.execute('DELETE FROM security_audits')
        connection.execute('PRAGMA user_version=1')
        raise failure('synthetic migration interruption')
    monkeypatch.setattr(migrations, 'MIGRATIONS', (interrupted,))
    with pytest.raises(failure):
        Database(repo)
    assert snapshot(path) == before
    monkeypatch.undo()
    assert Database(repo).latest_audit().id == 'legacy-audit'


@pytest.mark.parametrize('fail_second', [False, True])
def test_ordered_upgrades_commit_together_or_roll_back_together(legacy, monkeypatch, fail_second):
    repo, path, _ = legacy
    before = snapshot(path)
    steps = []
    first = migrations.MIGRATIONS[0]
    def step_one(connection):
        steps.append(connection.execute('PRAGMA user_version').fetchone()[0])
        first(connection)
    def step_two(connection):
        steps.append(connection.execute('PRAGMA user_version').fetchone()[0])
        connection.execute('CREATE TABLE future_metadata (name TEXT PRIMARY KEY)')
        connection.execute("UPDATE sessions SET ended_at='2026-10-09'")
        if fail_second:
            raise RuntimeError('synthetic second migration failure')
    monkeypatch.setattr(migrations, 'SCHEMA_VERSION', 2)
    monkeypatch.setitem(migrations.SCHEMAS, 2, (
        {**migrations.TABLES, 'future_metadata': (('name', 'TEXT', 0, 1),)}, migrations.INDEXES,
    ))
    monkeypatch.setattr(migrations, 'MIGRATIONS', (step_one, step_two))
    if fail_second:
        with pytest.raises(RuntimeError):
            Database(repo)
        assert snapshot(path) == before
    else:
        db = Database(repo)
        assert snapshot(path)['version'] == 2
        assert db.latest_session().ended_at == '2026-10-09'
        Database(repo)
        with sqlite3.connect(path) as connection:
            connection.execute('DROP TABLE future_metadata')
            connection.execute('PRAGMA user_version=1')
        Database(repo)  # A version 1 database upgrades using its historical layout.
        assert snapshot(path)['version'] == 2
        assert steps == [0, 1, 1]
        return
    assert steps == [0, 1]


def test_abrupt_process_exit_recovers_uncommitted_migration(legacy):
    repo, path, _ = legacy
    before = snapshot(path)
    script = '''
import os
import sys
from pathlib import Path
from infrastructure.database import migrations
from infrastructure.database.repository import Database
def crash(db):
    db.execute('CREATE TABLE unfinished (id TEXT)')
    db.execute('DELETE FROM security_audits')
    db.execute('PRAGMA user_version=1')
    os._exit(23)
migrations.MIGRATIONS = (crash,)
Database(Path(sys.argv[1]))
'''
    result = subprocess.run([sys.executable, '-c', script, str(repo)],
                            cwd=Path(__file__).resolve().parents[1], capture_output=True, timeout=15)
    assert result.returncode == 23, result.stderr
    assert snapshot(path) == before
    assert Database(repo).latest_audit().id == 'legacy-audit'


def test_simultaneous_legacy_startup_migrates_once_and_retains_all_writes(legacy, monkeypatch):
    repo, path, _ = legacy
    calls = []
    original = migrations.MIGRATIONS[0]
    def counted(connection):
        calls.append(1)
        original(connection)
    monkeypatch.setattr(migrations, 'MIGRATIONS', (counted,))
    barrier = threading.Barrier(6, timeout=10)
    def start(number):
        barrier.wait()
        db = Database(repo)
        db.start(Session(id=f'new-{number}', repository_path=str(repo), starting_commit='abc', branch='main'))
    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as workers:
        list(workers.map(start, range(6)))
    assert calls == [1]
    assert len(Database(repo).sessions()) == 7
    assert snapshot(path)['version'] == 1


