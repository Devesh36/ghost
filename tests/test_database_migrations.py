def test_future_database_cli_error_is_actionable_and_never_leaks_payloads(legacy, monkeypatch):
    repo, path, _ = legacy
    subprocess.run(['git', 'init', '-q', '--template=', str(repo)], check=True)
    subprocess.run(['git', '-C', str(repo), '-c', 'user.name=Test', '-c', 'user.email=test@example.invalid',
                    '-c', 'commit.gpgsign=false', 'commit', '--allow-empty', '-qm', 'initial'], check=True)
    with sqlite3.connect(path) as db:
        db.execute('PRAGMA user_version=99')
        db.execute("UPDATE security_audits SET payload='synthetic-private-payload'")
    before = path.read_bytes()
    monkeypatch.chdir(repo)
    response = CliRunner().invoke(app, ['status'])
    assert response.exit_code == 2
    assert 'Upgrade Ghost' in response.output and 'Traceback' not in response.output
    assert 'synthetic-private' not in response.output
    assert path.read_bytes() == before


