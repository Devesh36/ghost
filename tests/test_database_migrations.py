def test_failed_storage_access_never_stamps_a_version(legacy, monkeypatch):
    repo, path, _ = legacy
    before = path.read_bytes()
    import infrastructure.database.storage as storage_module
    original = storage_module.os.open
    def deny(name, *args, **kwargs):
        if name == 'ghost.db':
            raise PermissionError('synthetic denied storage read')
        return original(name, *args, **kwargs)
    monkeypatch.setattr(storage_module.os, 'open', deny)
    with pytest.raises(StorageError):
        Database(repo)
    assert path.read_bytes() == before


